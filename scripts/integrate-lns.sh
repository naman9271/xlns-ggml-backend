#!/usr/bin/env bash
# integrate-lns.sh — hook the LNS backends into a ggml source tree.
#
# Sourced by setup.sh and scripts/validate-latest.sh:
#   integrate_lns_or_fallback <repo> <patch> <base-commit>   # ggml or llama.cpp checkout
#   integrate_lns <ggml-root>                                 # only the edits
#   copy_lns_backends <ggml-root>                             # only the sources
# where <ggml-root> is a standalone ggml checkout or llama.cpp's ggml/.
#
# Two kinds of edits are made:
#
#   * The LNS16 tensor type: a GGML_TYPE_LNS16 slot in include/ggml.h and its
#     type traits in src/ggml.c. They are part of ggml's public type list, so
#     they are applied whichever backends are enabled.
#
#   * One hook set per backend in scripts/lns-backends.sh: a CMake option, a
#     ggml_add_backend() call, and the registry include + registration. They
#     are written as generated blocks between marker comments and rewritten on
#     every run, so integration is idempotent, registration order always
#     follows the manifest, and a new manifest row is all a new backend needs.
#
# Functions return 0 on success, 1 on failure.

LNS_INTEGRATE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LNS_REPO_ROOT="$(cd "$LNS_INTEGRATE_DIR/.." && pwd)"

# shellcheck source=lns-backends.sh
source "$LNS_INTEGRATE_DIR/lns-backends.sh"

# The ggml files the hooks touch, relative to <ggml-root>.
LNS_HOOKED_FILES=(CMakeLists.txt include/ggml.h src/CMakeLists.txt src/ggml-backend-reg.cpp src/ggml.c)

LNS_MARKER='xlns-ggml-backend:'

# lns_write_block FILE COMMENT TAG ANCHOR BLOCK
# Replaces the generated block TAG in FILE with BLOCK, or, the first time,
# inserts it right after the text matching the Perl regex ANCHOR.
lns_write_block() {
    LNS_C="$2" LNS_TAG="$3" LNS_ANCHOR="$4" LNS_BLOCK="$5" perl -0pi -e '
        my $begin = "$ENV{LNS_C} >>> xlns-ggml-backend: $ENV{LNS_TAG}";
        my $end   = "$ENV{LNS_C} <<< xlns-ggml-backend: $ENV{LNS_TAG}";
        my $text  = "$begin (generated by scripts/integrate-lns.sh, do not edit)\n$ENV{LNS_BLOCK}$end\n";
        my $anchor = $ENV{LNS_ANCHOR};
        unless (s/^\Q$begin\E[^\n]*\n.*?^\Q$end\E\n/$text/ms) {
            s/($anchor)/$1$text/m
                or die "integrate-lns: anchor for \"$ENV{LNS_TAG}\" not found in $ARGV\n";
        }
    ' "$1"
}

# ── LNS16 tensor type ────────────────────────────────────────────────────────

integrate_lns_type() {
    local root="$1"
    local header_file="$root/include/ggml.h"
    local ggml_c="$root/src/ggml.c"

    # ggml.h: take the current GGML_TYPE_COUNT value as the new slot.
    if ! grep -q 'GGML_TYPE_LNS16' "$header_file"; then
        perl -i -pe '
            if (/^(\s+)GGML_TYPE_COUNT\s*=\s*(\d+)\s*,/) {
                my $indent = $1;
                my $n = $2;
                $_ = "${indent}GGML_TYPE_LNS16   = $n, // 16-bit Logarithmic Number System (xlns16)\n"
                   . "${indent}GGML_TYPE_COUNT   = " . ($n + 1) . ",\n";
            }
        ' "$header_file" || return 1
        if ! grep -q 'GGML_TYPE_LNS16' "$header_file"; then
            echo "ERROR: integrate-lns: GGML_TYPE_COUNT anchor not found in ggml.h" >&2
            return 1
        fi
    fi

    # ggml.c: type traits, after the NVFP4 entry.
    if ! grep -q 'GGML_TYPE_LNS16' "$ggml_c"; then
        perl -i -0pe '
            s/(\[GGML_TYPE_NVFP4\] = \{.*?\},)\n(\s+\[GGML_TYPE_Q2_K\] = \{)/$1
    [GGML_TYPE_LNS16] = {
        .type_name                = "lns16",
        .blck_size                = 1,
        .type_size                = sizeof(uint16_t),
        .is_quantized             = false,
    },
$2/s
                or die "integrate-lns: NVFP4/Q2_K anchor not found in ggml.c\n";
        ' "$ggml_c" || return 1
    fi
}

# ── Backend hooks ────────────────────────────────────────────────────────────

integrate_lns_backends() {
    local root="$1"
    local row fn options="" add_backends="" includes="" registrations=""
    for row in "${LNS_BACKENDS[@]}"; do
        lns_backend_row "$row"
        options+="option(GGML_${LNS_NAME} \"${LNS_DESCRIPTION}\" OFF)"$'\n'
        add_backends+="ggml_add_backend(${LNS_NAME})"$'\n'
        includes+="#ifdef GGML_USE_${LNS_NAME}"$'\n'"#include \"${LNS_HEADER}\""$'\n'"#endif"$'\n'
        registrations+="#ifdef GGML_USE_${LNS_NAME}"$'\n'
        for fn in $LNS_REG_FNS; do
            registrations+="        register_backend(${fn}());"$'\n'
        done
        registrations+="#endif"$'\n'
    done

    lns_write_block "$root/CMakeLists.txt" '#' 'LNS backend options' \
        '^option\(GGML_BLAS\s[^\n]*\n' "$options" || return 1
    lns_write_block "$root/src/CMakeLists.txt" '#' 'LNS backends' \
        '^ggml_add_backend\(BLAS\)[^\n]*\n' "$add_backends" || return 1
    lns_write_block "$root/src/ggml-backend-reg.cpp" '//' 'LNS backend headers' \
        '^#ifdef GGML_USE_BLAS\n#include "ggml-blas.h"\n#endif\n' "$includes" || return 1
    lns_write_block "$root/src/ggml-backend-reg.cpp" '//' 'LNS backend registration' \
        '^#ifdef GGML_USE_BLAS\n\s*register_backend\(ggml_backend_blas_reg\(\)\);\n#endif\n' "$registrations" || return 1
}

integrate_lns_validate() {
    local root="$1"
    local errors=0 row f count

    for f in "${LNS_HOOKED_FILES[@]}"; do
        if [ ! -f "$root/$f" ]; then
            echo "ERROR: validate: missing file $root/$f" >&2
            return 1
        fi
    done

    count=$(grep -c 'GGML_TYPE_LNS16' "$root/include/ggml.h" || true)
    [ "$count" -eq 1 ] || { echo "ERROR: validate: expected 1 GGML_TYPE_LNS16 in ggml.h, found $count" >&2; errors=1; }
    grep -q 'GGML_TYPE_LNS16' "$root/src/ggml.c" \
        || { echo "ERROR: validate: LNS16 type traits missing from ggml.c" >&2; errors=1; }

    for f in CMakeLists.txt src/CMakeLists.txt src/ggml-backend-reg.cpp; do
        count=$(grep -c ">>> $LNS_MARKER" "$root/$f" || true)
        local expected=1
        [ "$f" = src/ggml-backend-reg.cpp ] && expected=2
        [ "$count" -eq "$expected" ] \
            || { echo "ERROR: validate: expected $expected generated block(s) in $f, found $count" >&2; errors=1; }
    done

    for row in "${LNS_BACKENDS[@]}"; do
        lns_backend_row "$row"
        count=$(grep -c "^option(GGML_${LNS_NAME} " "$root/CMakeLists.txt" || true)
        [ "$count" -eq 1 ] || { echo "ERROR: validate: expected 1 option(GGML_${LNS_NAME}), found $count" >&2; errors=1; }
        count=$(grep -c "^ggml_add_backend(${LNS_NAME})" "$root/src/CMakeLists.txt" || true)
        [ "$count" -eq 1 ] || { echo "ERROR: validate: expected 1 ggml_add_backend(${LNS_NAME}), found $count" >&2; errors=1; }
        count=$(grep -c "^#ifdef GGML_USE_${LNS_NAME}\$" "$root/src/ggml-backend-reg.cpp" || true)
        [ "$count" -eq 2 ] || { echo "ERROR: validate: expected GGML_USE_${LNS_NAME} include + registration, found $count" >&2; errors=1; }
    done

    return "$errors"
}

integrate_lns() {
    local root="$1"
    integrate_lns_type "$root" || return 1
    integrate_lns_backends "$root" || return 1
    integrate_lns_validate "$root"
}

# Trees hooked by the pre-manifest version of this script carry LNS hooks
# outside the generated blocks. Those cannot be updated in place, so the
# hooked files are restored from git and integrated afresh.
lns_reset_legacy_hooks() {
    local root="$1"
    local reg_file="$root/src/ggml-backend-reg.cpp"
    if grep -q 'GGML_USE_LNS' "$reg_file" && ! grep -q "$LNS_MARKER" "$reg_file"; then
        echo "    Found hooks from an older integrate-lns.sh; restoring the hooked files from git"
        git -C "$root" checkout -- "${LNS_HOOKED_FILES[@]}" || return 1
        if [ -f "$root/examples/simple/CMakeLists.txt" ]; then
            git -C "$root" checkout -- examples/simple/CMakeLists.txt || return 1
        fi
    fi
}

lns_ggml_root() {
    if [ -f "$1/ggml/include/ggml.h" ]; then
        echo "$1/ggml"
    else
        echo "$1"
    fi
}

integrate_lns_or_fallback() {
    local repo_dir="$1"       # ggml or llama.cpp checkout root
    local patch_file="$2"
    local base_commit="$3"
    local ggml_root
    ggml_root="$(lns_ggml_root "$repo_dir")"

    lns_reset_legacy_hooks "$ggml_root" || return 1

    if integrate_lns "$ggml_root"; then
        echo "    Integration succeeded"
        return 0
    fi

    echo "    Regex integration failed; using patch fallback"
    cd "$repo_dir" || return 1
    git reset --hard "$base_commit" || return 1
    if ! git apply "$patch_file"; then
        echo "ERROR: patch fallback also failed" >&2
        return 1
    fi
    # The patch was recorded at the pinned commit; refresh the generated
    # blocks in case the manifest has changed since.
    integrate_lns "$ggml_root"
}

# ── Sources ──────────────────────────────────────────────────────────────────

# Copies every backend in the manifest, its public header and the shared
# sources into the tree. Destination directories are replaced, not merged, so
# files deleted from this repo do not linger in the build tree.
copy_lns_backends() {
    local root="$1"
    local row dest
    dest="$root/src/ggml-lns-common"
    rm -rf "$dest" && mkdir -p "$dest" || return 1
    cp -R "$LNS_REPO_ROOT/$LNS_COMMON_SOURCES/." "$dest/" || return 1
    for row in "${LNS_BACKENDS[@]}"; do
        lns_backend_row "$row"
        dest="$root/src/ggml-$(echo "$LNS_NAME" | tr '[:upper:]' '[:lower:]')"
        rm -rf "$dest" && mkdir -p "$dest" || return 1
        cp -R "$LNS_REPO_ROOT/$LNS_SOURCES/." "$dest/" || return 1
        cp "$LNS_REPO_ROOT/lns-backend/include/$LNS_HEADER" "$root/include/" || return 1
    done
}

# Adds the LNS unit tests to a standalone ggml tree's examples/simple.
copy_lns_tests() {
    local root="$1"
    local test_dir="$root/examples/simple"
    cp "$LNS_REPO_ROOT/lns-backend/tests/test-lns-backend.cpp" "$test_dir/" || return 1
    cp "$LNS_REPO_ROOT/lns-backend/tests/test-lns-cuda-parity.cpp" "$test_dir/" || return 1
    lns_write_block "$test_dir/CMakeLists.txt" '#' 'LNS tests' '\z' '
if (GGML_LNS)
    add_executable(test-lns-backend test-lns-backend.cpp)
    target_link_libraries(test-lns-backend PRIVATE ggml)
endif()
if (GGML_LNS AND GGML_LNS32 AND GGML_LNSCUDA)
    add_executable(test-lns-cuda-parity test-lns-cuda-parity.cpp)
    target_link_libraries(test-lns-cuda-parity PRIVATE ggml)
endif()
'
}
